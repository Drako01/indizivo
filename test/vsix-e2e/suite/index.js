'use strict';
const assert=require('node:assert/strict');
const vscode=require('vscode');
exports.run=async function run() {
 const extension=vscode.extensions.getExtension('armotusitio.indizivo');
 assert.ok(extension,'Installed VSIX must be discovered from isolated --extensions-dir');
 assert.equal(extension.packageJSON.version,process.env.INDIZIVO_TEST_EXPECTED_VERSION);
 assert.equal(process.env.INDIZIVO_PACKAGED_TEST,'true');
 const api=await extension.activate();
 assert.ok(api?.controller,'Packaged extension should export its controller');
 const controller=api.controller;
 assert.ok(vscode.workspace.workspaceFolders?.length===1);
 await vscode.commands.executeCommand('indizivo.openHome');
 assert.ok(controller.panel,'Packaged webview must open');
 await vscode.commands.executeCommand('indizivo.diagnose');
 assert.equal(controller.data.session?.state,'completed');
 assert.ok(controller.data.session.checks.some(c=>c.id==='node'));
 assert.ok(controller.data.session.checks.some(c=>c.id==='port-32998'));
 assert.ok(controller.data.session.checks.some(c=>c.id==='env'));
 await controller.setLocale('es');
 assert.equal(controller.snapshot().locale,'es');
 await controller.selectHistory(0);
 assert.equal(controller.snapshot().reviewMode,true);
 await controller.selectHistory(-1);
 assert.equal(controller.snapshot().reviewMode,false);
 controller.panel.dispose();
 assert.equal(controller.panel,null);
 console.log('Packaged VSIX extension host smoke passed');
};
